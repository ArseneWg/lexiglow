import { readFile, writeFile, mkdir } from "node:fs/promises";

const CMUDICT_REVISION = "74790861f652b15e4ac49015a90074ad62a27690";
const BRITFONE_REVISION = "1062be14adc96c358f2087ac5449d72130c7a6f4";
const CMUDICT_URL = "https://raw.githubusercontent.com/cmusphinx/cmudict/" + CMUDICT_REVISION + "/cmudict.dict";
const BRITFONE_URL = "https://raw.githubusercontent.com/JoseLlarena/Britfone/" + BRITFONE_REVISION + "/britfone.main.3.0.1.csv";
const CORE_PRONUNCIATION_LIMIT = 5000;
const EXTENDED_PRONUNCIATION_LIMIT = 10000;
const EXTRA_WORDS = [
  "block", "blocks", "bus", "buses", "dog", "dogs", "look", "looked", "play", "played", "want", "wanted",
  "refuse", "record", "lead", "live", "read", "present", "object", "close", "use", "used", "obfuscation",
  "measure", "measuring",
];

async function download(url) {
  const response = await fetch(url, { headers: { "user-agent": "LexiGlow-pronunciation-data-builder" } });
  if (!response.ok) throw new Error("Failed to download " + url + ": " + response.status);
  return response.text();
}

const lexicon = await readFile(new URL("../data/google-10000-english.txt", import.meta.url), "utf8");
const rankedWords = lexicon
  .split(/\r?\n/)
  .map((line) => line.trim().toLowerCase())
  .filter(Boolean)
  .slice(0, EXTENDED_PRONUNCIATION_LIMIT);
const coreWanted = new Set(rankedWords.slice(0, CORE_PRONUNCIATION_LIMIT));
EXTRA_WORDS.forEach((word) => coreWanted.add(word));
const extendedWanted = new Set(
  rankedWords.slice(CORE_PRONUNCIATION_LIMIT, EXTENDED_PRONUNCIATION_LIMIT)
    .filter((word) => !coreWanted.has(word)),
);

const [cmuRaw, britRaw] = await Promise.all([download(CMUDICT_URL), download(BRITFONE_URL)]);
const usCore = {};
const usExtended = {};
for (const line of cmuRaw.split(/\r?\n/)) {
  const match = line.match(/^([^\s]+)\s+(.+)$/);
  if (!match) continue;
  const head = (match[1] || "").replace(/\(\d+\)$/u, "").toLowerCase();
  const target = coreWanted.has(head) ? usCore : extendedWanted.has(head) ? usExtended : null;
  if (!target) continue;
  (target[head] ||= []).push((match[2] || "").trim());
}

const ukCore = {};
const ukExtended = {};
for (const line of britRaw.split(/\r?\n/)) {
  const comma = line.indexOf(",");
  if (comma <= 0) continue;
  const rawHead = line.slice(0, comma).trim().replace(/\(\d+\)$/u, "");
  if (rawHead.includes("_")) continue;
  const head = rawHead.toLowerCase();
  const target = coreWanted.has(head) ? ukCore : extendedWanted.has(head) ? ukExtended : null;
  if (!target) continue;
  const ipa = line.slice(comma + 1).trim().replace(/\s+/g, "");
  if (!ipa) continue;
  (target[head] ||= []).push("/" + ipa + "/");
}

for (const map of [usCore, usExtended, ukCore, ukExtended]) {
  for (const key of Object.keys(map)) map[key] = [...new Set(map[key])];
}

const sorted = (map) => Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
const revision = "cmudict:" + CMUDICT_REVISION + ";britfone:" + BRITFONE_REVISION +
  ";core:" + CORE_PRONUNCIATION_LIMIT + ";extended:" + EXTENDED_PRONUNCIATION_LIMIT;
const coreOutput = [
  "// Generated by scripts/refresh-pronunciation-data.mjs. Do not edit by hand.",
  "export const PRONUNCIATION_DATA_REVISION = " + JSON.stringify(revision) + ";",
  "export const LOCAL_US_ARPABET = " + JSON.stringify(sorted(usCore), null, 2) + " as const;",
  "export const LOCAL_UK_IPA = " + JSON.stringify(sorted(ukCore), null, 2) + " as const;",
  "",
].join("\n");
const extendedOutput = [
  "// Generated by scripts/refresh-pronunciation-data.mjs. Do not edit by hand.",
  "export const EXTENDED_LOCAL_US_ARPABET = " + JSON.stringify(sorted(usExtended), null, 2) + " as const;",
  "export const EXTENDED_LOCAL_UK_IPA = " + JSON.stringify(sorted(ukExtended), null, 2) + " as const;",
  "",
].join("\n");

await mkdir(new URL("../src/generated", import.meta.url), { recursive: true });
await Promise.all([
  writeFile(new URL("../src/generated/pronunciationData.ts", import.meta.url), coreOutput, "utf8"),
  writeFile(new URL("../src/generated/pronunciationDataExtended.ts", import.meta.url), extendedOutput, "utf8"),
]);
console.log(
  "Generated pinned pronunciation fallback: core " + CORE_PRONUNCIATION_LIMIT +
  " (" + Object.keys(usCore).length + " US / " + Object.keys(ukCore).length + " UK), extended to " +
  EXTENDED_PRONUNCIATION_LIMIT + " (" + Object.keys(usExtended).length + " US / " + Object.keys(ukExtended).length + " UK).",
);
